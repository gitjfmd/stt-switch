#!/usr/bin/env bash
# check-pr-stamp.sh — FAIL a PR body that lacks the agent provenance stamp.
#
# RULE (designed 2026-11-16; CEO 2026-11-15/16 footprint, canonical field set
# quoted 2026-11-15: "cli name/session-id/the name of the session/date, time,
# and the message I sent for that work, the branch it was worked in, and list of
# parallel agents or subagents with their id/sessions, the jsonl location on mac
# for that, or if cross cli then mention which cli"). The check PASSES iff:
#   (a) the body carries the stamp in the CEO's canonical field set — every
#       field below present with a non-empty value ("none" is an explicit,
#       accepted value for session-name and agents), OR
#   (b) the body declares exactly `human PR, no stamp` on its own line (a human
#       PR has no agent session to stamp).
# Anything else FAILS and names the missing fields.
#
# Bot-authored PRs (renovate, github-actions, any `<name>[bot]` actor) are
# exempt at the WORKFLOW level (.github/workflows/pr-stamp.yml), not here: this
# script only ever sees the body.
#
# Required fields (verbatim names, the CEO's order):
#   cli:          <cli name> (cross-CLI named here when the work was done by a
#                 different CLI than the repo owner)
#   session-id:   <uuid> (or the compact `<TS>-<short>` session id some CLIs use)
#   session-name: <the name of the session>
#   datetime:     <UTC ISO8601>
#   message:      "<the operator message that commissioned this work, verbatim>"
#   branch:       <the branch it was worked in>
#   agents:       "none", or one `  - <role>: <cli>/<session-id> · jsonl: <path>`
#                 line per parallel agent/subagent
#
# The stamp is GENERATED by scripts/agent-commit-identity.sh (AGENT_PR_STAMP /
# AGENT_PR_RECORD): source that and paste, or run
# `bash scripts/check-pr-stamp.sh --print` to emit the current session's block.
# Commit trailers keep the compact Agent-Session form (that is a different
# surface; this gate is the PR BODY).
#
# PR-OPEN GATE (operations/policies/PR-OPEN-GATE.md): run this on the planned
# body BEFORE `gh pr create`; the gate FAILS if this exits non-zero. The
# required CI check "agent provenance stamp present" is the merge-time backstop.
#
# Usage:
#   bash scripts/check-pr-stamp.sh <body-file>    # file, or - for stdin
#   bash scripts/check-pr-stamp.sh --pr <n>       # fetch body via gh
#   bash scripts/check-pr-stamp.sh --print        # emit this session's stamp
# Exit: 0 pass, 1 fail (missing fields on stdout), 2 usage/lookup error.
set -uo pipefail

# session id: UUID or the compact "<TS>-<short>" form some CLIs export.
UUID='[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}'
TSID='[0-9]{8}T[0-9]{6}-[0-9]+'

case "${1:-}" in
  --print)
    top="$(git rev-parse --show-toplevel 2>/dev/null)" || { echo "not inside a git repo" >&2; exit 2; }
    lib="$top/scripts/agent-commit-identity.sh"
    [ -r "$lib" ] || lib="$HOME/.local/lib/agent-commit-identity.sh"
    [ -r "$lib" ] || { echo "no agent-commit-identity.sh found" >&2; exit 2; }
    # shellcheck source=/dev/null
    . "$lib" "$top" >/dev/null 2>&1
    printf '%s\n' "${AGENT_PR_RECORD:-}"
    exit 0
    ;;
  --pr)
    body="$(mktemp)" || exit 2
    trap 'rm -f "$body"' EXIT
    gh pr view "${2:?pr number}" --json body --jq .body > "$body" 2>/dev/null || exit 2
    ;;
  -|"")
    body="$(mktemp)" || exit 2
    trap 'rm -f "$body"' EXIT
    cat > "$body"
    ;;
  *)
    body="$1"
    [ -f "$body" ] || { echo "no such body file: $body" >&2; exit 2; }
    ;;
esac

# (b) the human declaration is its own pass.
grep -qiE '^[[:space:]]*human PR, no stamp[[:space:]]*$' "$body" && { echo "PASS: human PR declaration"; exit 0; }

fail=0
field() { # field <label> <present?> <hint>
  if [ "$2" = 1 ]; then printf '  ok   %s\n' "$1"; else printf '  MISS %s — %s\n' "$1" "$3"; fail=1; fi
}

grep -qE '^cli: [^[:space:]]' "$body" && c=1 || c=0
field "cli:" "$c" 'add "cli: <cli name>" (name the cross-CLI here when applicable)'

grep -qE "^session-id: ($UUID|$TSID)" "$body" && c=1 || c=0
field "session-id:" "$c" 'add "session-id: <uuid>"'

grep -qE '^session-name: .+' "$body" && c=1 || c=0
field "session-name:" "$c" 'add "session-name: <the name of the session>" (or "none" when the store has none)'

grep -qE '^datetime: [0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}' "$body" && c=1 || c=0
field "datetime:" "$c" 'add "datetime: <UTC ISO8601>"'

grep -qE '^message: .+' "$body" && c=1 || c=0
field "message:" "$c" 'add "message: \\"<the operator message, verbatim>\\""'

bv="$(grep -m1 -E '^branch: ' "$body" | sed 's/^branch:[[:space:]]*//')"
if [ -n "$bv" ] && [ "$bv" != "unknown" ]; then c=1; else c=0; fi
field "branch:" "$c" 'add "branch: <the branch it was worked in>" (unknown does not count)'

# agents: "none" inline, any inline value, or `agents:` + `  - ...` roster lines.
if grep -qE '^agents: [^[:space:]]' "$body" || { grep -qE '^agents:[[:space:]]*$' "$body" && grep -qE '^  - .+' "$body"; }; then
  c=1
else
  c=0
fi
field "agents:" "$c" 'add "agents: none" or an "agents:" roster with "  - <role>: <cli>/<session-id> · jsonl: <path>" lines'

if [ "$fail" -eq 0 ]; then
  echo "PASS: provenance stamp complete"
  exit 0
fi
echo "FAIL: provenance stamp incomplete — generate it with: bash scripts/check-pr-stamp.sh --print"
exit 1
